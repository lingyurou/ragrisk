def _norm(s):
    return re.sub(r"\s+", "", s)


_txt_cache = {}


def doc_text(doc_id):
    if doc_id not in _txt_cache:
        _txt_cache[doc_id] = open(os.path.join(HERE, "raw", doc_id + ".txt"),
                                  encoding="utf-8").read()
    return _txt_cache[doc_id]


def verify():
    """Every prov='doc' unit's quote must be a verbatim substring of its doc."""
    bad = []
    for r in U:
        if r.prov != "doc":
            continue
        if _norm(r.quote) not in _norm(doc_text(r.doc)):
            bad.append((r.doc, r.clause, r.quote[:40]))
    return bad


def unit_text(r):
    if r.prov == "doc":
        title = DOCS[r.doc][0]
        return f"《{title}》{r.clause}：{r.quote}"
    return r.quote


def build_real_kb():
    bad = verify()
    if bad:
        raise SystemExit("quote verification failed:\n" + "\n".join(map(str, bad)))
    units = []
    for i, r in enumerate(U, 1):
        units.append(Unit(
            uid=f"r{i}", doc_id=r.doc, tier=r.tier, product=r.product, attr=r.attr,
            value=r.value, unit=r.unit, region=r.region, segment=r.segment,
            valid_from=r.vf, valid_to=r.vt, tx_version=0, text=unit_text(r),
            ver=r.ver, grant=r.grant))
    return units


