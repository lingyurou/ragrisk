def _num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def laxer_real(u1, v1):
    """Laxer-than-regulation test under the attr's direction; None if incomparable."""
    mode = MODE.get(u1.attr)
    if mode is None:
        return None
    a, b = _num(u1.value), _num(v1.value)
    if a is None or b is None:
        return None
    if mode == "floor":
        return a < b
    return a > b


def resolve_real(units, ctx):
    """Same R1-R5 pipeline as the benchmark, with real-instrument tiers:
    operative = L1 (法律法规) and L2 (部门规章/规范性文件); L5 marketing is
    never governing.  R1 drops institutional units laxer than a higher-tier
    applicable norm unless explicitly transitional (grant)."""
    cands = [u for u in units
             if u.product == ctx["product"] and u.attr == ctx["attr"]
             and u.region in ("全部", ctx["region"])
             and u.segment in ("全部客户", ctx["segment"])
             and u.valid_from <= ctx["t_ref"] < u.valid_to]
    if not cands:
        return [], []
    op = [u for u in cands if u.tier in OPERATIVE_REAL]
    if not op:
        return [], cands
    adm = []
    for a in op:
        ok = True
        if not a.grant:
            for b in op:
                if TIER_RANK[b.tier] < TIER_RANK[a.tier] and laxer_real(a, b) is True:
                    ok = False
                    break
        if ok:
            adm.append(a)
    if not adm:
        return [], op
    spec = lambda x: (x.region != "全部") + (x.segment != "全部客户")   # noqa: E731
    ms = max(spec(x) for x in adm)
    pool = [x for x in adm if spec(x) == ms]
    top = min(TIER_RANK[x.tier] for x in pool)
    pool = [x for x in pool if TIER_RANK[x.tier] == top]
    pool.sort(key=lambda x: -x.valid_from)
    best = pool[0]
    for x in pool:
        if laxer_real(best, x) is True:
            best = x
    return [best], op


